  /** 받침이 있으면 withFinal ("지수님" + 은/는). */
  function josa(word, withFinal, withoutFinal) {
    var code = word.charCodeAt(word.length - 1) - 0xac00;
    if (code < 0 || code > 11171) return word + withFinal;
    return word + (code % 28 ? withFinal : withoutFinal);
  }

  /** 이름 자리 꼴: {A}, {A은}, {A이}, {A을}, {A과}, {A의}, {A에게}. "나"는 "내가", "내"로 바꾼다. */
  function nameForm(who, form) {
    var me = who === "나";
    switch (form) {
      case "은": return josa(who, "은", "는");
      case "이": return me ? "내가" : josa(who, "이", "가");
      case "을": return josa(who, "을", "를");
      case "과": return josa(who, "과", "와");
      case "의": return me ? "내" : who + "의";
      case "에게": return who + "에게";
      default: return who;
    }
  }

  function fill(template, a, b, extra) {
    return template.replace(/\{(A|B|X|Y)(은|이|을|과|의|에게)?\}/g, function (_, who, form) {
      if (who === "A") return nameForm(a.who, form || "");
      if (who === "B") return nameForm(b.who, form || "");
      return extra[who];
    });
  }

